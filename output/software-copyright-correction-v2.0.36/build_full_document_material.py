def add_section(doc, title, paragraphs, bullets):
    add_heading(doc, title, 1)
    for paragraph in paragraphs:
        add_text(doc, paragraph, size=10.2, after=5, line=1.22)
    for bullet in bullets:
        add_bullet(doc, bullet)


